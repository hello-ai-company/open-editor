export default async (page) => {
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => { const url = route.request().url(); if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//.test(url) && !/^(data|blob):/.test(url)) { external.push(url); return route.abort(); } return route.continue(); });
  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:5199/?notes=synthetic');
  await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  const title = page.locator('.oe-notes-document-header input');
  await page.getByRole('combobox', {name:'合成workspace保存障害'}).selectOption('lost-ack');
  await title.fill('応答喪失でも保持するタイトル');
  await page.locator('.oe-notes-workspace-header').getByRole('button', {name:'保存',exact:true}).click();
  await page.locator('.oe-notes-save-feedback').getByRole('button', {name:'保存結果を照会',exact:true}).waitFor();
  if (await title.inputValue() !== '応答喪失でも保持するタイトル') throw new Error('Lost ACK draft lost');
  await page.locator('.oe-notes-save-feedback').getByRole('button', {name:'保存結果を照会',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.oe-notes-workspace-header [role=status]')?.textContent === '保存を確認済み', {timeout:10000}).catch(async () => { await page.screenshot({path:'OUTPUT/workspace-flow-failure.png'}); throw new Error(await page.locator('.oe-notes-save-feedback').innerText()); });
  await page.getByRole('combobox', {name:'合成workspace保存障害'}).selectOption('none');
  await page.reload(); await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  if (await title.inputValue() !== '応答喪失でも保持するタイトル') throw new Error('Confirmed title reload lost');
  await page.getByRole('button', {name:'ドキュメント',exact:true}).click();
  await page.getByRole('tab', {name:'コメント',exact:true}).click();
  await page.getByRole('textbox', {name:'コメント本文',exact:true}).fill('まだ保存していない入力');
  await page.getByRole('tab', {name:'行のノート',exact:true}).click();
  if (await title.inputValue() !== '応答喪失でも保持するタイトル') throw new Error('Pending form allowed tab leave');
  const backup = page.waitForEvent('download'); await page.getByRole('button', {name:'入力を退避',exact:true}).click(); await backup;
  await page.getByRole('button', {name:'入力を取り消す',exact:true}).click();
  await page.getByRole('tab', {name:'行のノート',exact:true}).click();
  await page.locator('.oe-synthetic-row-tools').waitFor();
  await page.getByRole('textbox', {name:'名前の値',exact:true}).fill('行の入力');
  await page.getByRole('tab', {name:/応答喪失|移管の合成ノート/}).click();
  await page.locator('.oe-synthetic-row-tools').waitFor();
  await page.getByRole('button', {name:'最新値に戻す',exact:true}).first().click();
  await page.getByRole('tab', {name:/応答喪失|移管の合成ノート/}).click();
  await page.locator('.oe-notes-document-header input').waitFor();
  // Modal picker cancellation makes no local insertion and returns keyboard focus.
  await page.locator('.oe-notes-workspace-right').getByRole('tab', {name:'挿入',exact:true}).click();
  await page.getByRole('button', {name:'リンク',exact:true}).click();
  await page.getByRole('dialog', {name:'リンクを追加'}).waitFor();
  await page.keyboard.press('Escape');
  if (await page.getByRole('dialog', {name:'リンクを追加'}).isVisible()) throw new Error('Picker cancel failed');
  await page.setViewportSize({width:320,height:760});
  for (const side of ['ノート','編集ツール']) {
    await page.getByRole('button', {name:side,exact:true}).click();
    const drawer = page.getByRole('dialog', {name:side === 'ノート' ? 'ノートを選択' : '編集ツール',exact:true});
    await drawer.waitFor();
    const geometry = await drawer.boundingBox();
    if (!geometry || geometry.x < 0 || geometry.x + geometry.width > 321 || geometry.y < 0) throw new Error('Drawer geometry');
    await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Tab');
    if (!await drawer.evaluate(node => node.contains(document.activeElement))) throw new Error('Drawer focus escaped');
    if (!await page.locator('.oe-notes-workspace-document').evaluate(node => node.inert)) throw new Error('Background is active');
    await drawer.dispatchEvent('keydown', {key:'Escape',isComposing:true});
    if (!await drawer.isVisible()) throw new Error('IME escape closed drawer');
    await page.keyboard.press('Escape');
    if (await drawer.isVisible()) throw new Error('Drawer escape failed');
    if (!await page.getByRole('button', {name:side,exact:true}).evaluate(node => node === document.activeElement)) throw new Error('Opener focus lost');
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.screenshot({path:'OUTPUT/workspace-final-mobile.png'});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error('Overflow');
  if (errors.length || external.length) throw new Error(JSON.stringify({errors,external}));
  return {lostAckLookupReload:true,pendingCommentTabGuard:true,localDraftBackup:true,rowDraftGuard:true,pickerCancel:true,mobileFocusInertIme:true,reducedMotion:true,errors,externalRequests:external.length};
};
