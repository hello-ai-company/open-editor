export default async (page) => {
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => { const url = route.request().url(); if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//.test(url) && !/^(data|blob):/.test(url)) { external.push(url); return route.abort(); } return route.continue(); });
  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:5199/?notes=synthetic');
  await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  await page.getByRole('button', {name:'HTML ウィジェット',exact:true}).click();
  const widget = page.getByRole('region', {name:'HTML widget',exact:true});
  if (await widget.locator('iframe').getAttribute('sandbox') !== '' || !(await widget.locator('iframe').getAttribute('srcdoc')).includes("script-src 'none'")) throw new Error('HTML preview isolation missing');
  await widget.getByRole('button', {name:'Edit source',exact:true}).click();
  const html = widget.getByRole('textbox', {name:'HTML source',exact:true});
  await html.fill('<h2>残すソース</h2>');
  await page.getByRole('tab', {name:'行のノート',exact:true}).click();
  if (await html.inputValue() !== '<h2>残すソース</h2>') throw new Error('HTML source lost on navigation');
  await html.dispatchEvent('compositionstart');
  await html.dispatchEvent('keydown', {key:'Escape',isComposing:true});
  if (!await html.isVisible()) throw new Error('HTML IME Escape closed');
  await html.dispatchEvent('compositionend');
  await widget.getByRole('button', {name:'Apply source',exact:true}).click();
  if (await html.isVisible()) throw new Error('HTML apply did not close');
  await page.locator('.oe-notes-workspace-header').getByRole('button', {name:'保存',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.oe-notes-workspace-header [role=status]')?.textContent === '保存を確認済み');
  await page.reload(); await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  await page.getByRole('region', {name:'HTML widget',exact:true}).getByRole('button', {name:'Edit source',exact:true}).click();
  if (await page.getByRole('textbox', {name:'HTML source',exact:true}).inputValue() !== '<h2>残すソース</h2>') throw new Error('HTML source reload lost');
  await page.getByRole('region', {name:'HTML widget',exact:true}).getByRole('button', {name:'Cancel',exact:true}).click();
  await page.getByRole('button', {name:'ホワイトボード',exact:true}).click();
  const drawing = page.locator('.oe-notes-drawing'); await drawing.waitFor();
  const canvas = drawing.locator('svg'), rect = await canvas.boundingBox();
  if (!rect) throw new Error('Drawing invisible');
  await page.mouse.move(rect.x+40,rect.y+40); await page.mouse.down(); await page.mouse.move(rect.x+90,rect.y+70,{steps:5}); await page.mouse.up();
  const png = page.waitForEvent('download'); await drawing.getByRole('button', {name:'Export PNG',exact:true}).click(); await png;
  await drawing.getByRole('button', {name:'Undo drawing',exact:true}).click();
  await drawing.getByRole('button', {name:'Redo drawing',exact:true}).click();
  await page.screenshot({path:'OUTPUT/workspace-widgets-desktop.png'});
  await page.locator('.oe-notes-workspace-header').getByRole('button', {name:'保存',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.oe-notes-workspace-header [role=status]')?.textContent === '保存を確認済み');
  if (errors.length || external.length) throw new Error(JSON.stringify({errors,external}));
  return {htmlPendingTabGuard:true,htmlImeCancel:true,htmlApplyReload:true,safeIframe:true,drawingPointerUndoRedo:true,pngDownload:true,errors,externalRequests:external.length};
};
