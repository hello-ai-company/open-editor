export default async (page) => {
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => { const url = route.request().url(); if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//.test(url) && !/^(data|blob):/.test(url)) { external.push(url); return route.abort(); } return route.continue(); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:5199/?notes=synthetic');
  await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  await page.screenshot({ path: 'OUTPUT/workspace-desktop.png', fullPage: false });
  await page.getByRole('button', { name: 'ドキュメント', exact: true }).click();
  await page.getByRole('tab', { name: 'タスク', exact: true }).click();
  await page.getByRole('button', { name: '移管を再読込で確認するを完了にする', exact: true }).click();
  await page.locator('.oe-notes-workspace-header').getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.oe-notes-workspace-header [role=status]')?.textContent === '保存を確認済み');
  await page.reload();
  await page.locator('.oe-notes-blocknote-document .bn-editor').waitFor();
  await page.getByRole('button', { name: 'ドキュメント', exact: true }).click();
  await page.getByRole('tab', { name: 'タスク', exact: true }).click();
  if (await page.getByRole('button', { name: '移管を再読込で確認するを未完了にする', exact: true }).getAttribute('aria-pressed') !== 'true') throw new Error('Task reload lost');
  await page.getByRole('tab', { name: 'コメント', exact: true }).click();
  await page.getByRole('textbox', { name: 'コメント本文', exact: true }).fill('合成のコメントを保持');
  await page.getByRole('combobox', { name: 'コメントの対象ブロック' }).selectOption({index:1});
  await page.getByRole('button', { name: 'コメントを追加', exact: true }).click();
  await page.getByText('合成のコメントを保持', { exact: true }).waitFor();
  await page.getByRole('tab', { name: '書式', exact: true }).click();
  await page.getByRole('button', { name: '等幅フォント', exact: true }).click();
  await page.getByRole('button', { name: 'テンプレート', exact: true }).click();
  await page.getByRole('button', { name: '閉じる', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 760 });
  await page.getByRole('button', { name: '編集ツール', exact: true }).click();
  await page.locator('.oe-notes-workspace-right').getByRole('tab', { name: '情報', exact: true }).click();
  await page.screenshot({ path: 'OUTPUT/workspace-mobile-tools.png' });
  await page.keyboard.press('Escape');
  if (await page.locator('.oe-notes-workspace-right').isVisible()) throw new Error('Drawer remained open');
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error('Horizontal overflow');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.screenshot({ path: 'OUTPUT/workspace-mobile-document.png' });
  if (errors.length || external.length) throw new Error(JSON.stringify({ errors, external }));
  return { taskPersistReload: true, commentCommit: true, styleAction: true, templateCancel: true, mobile320: true, drawerEscape: true, reducedMotion: true, errors, externalRequests: external.length };
};
